const generatedHeader = "# Generated by go run ./cmd/cli openapi generate. Edit handler DTOs/routes or docs/openapi.overrides.yaml.\n"

// Generate combines real registered routes with typed handler contracts. Only
// summaries/descriptions are inherited from overrides; stale routes are dropped.
func Generate(dir string) ([]byte, error) {
	source, err := loadSources(dir)
	if err != nil {
		return nil, err
	}
	var overrides object
	if data, err := os.ReadFile(filepath.Join(dir, "docs/openapi.overrides.yaml")); err == nil {
		if err := yaml.Unmarshal(data, &overrides); err != nil {
			return nil, err
		}
	} else {
		return nil, err
	}
	components, _ := overrides["components"].(map[string]any)
	if components == nil {
		components = object{}
	}
	definitions, _ := components["schemas"].(map[string]any)
	if definitions == nil {
		definitions = object{}
	}
	components["schemas"] = definitions
	components["securitySchemes"] = object{
		"bearerAuth":          object{"type": "http", "scheme": "bearer", "bearerFormat": "JWT"},
		"sessionCookie":       object{"type": "apiKey", "in": "cookie", "name": "sso_session", "description": "Existing HttpOnly server-side session cookie; sign in through the portal. Swagger UI cannot set this cookie manually."},
		"legacyAccessCookie":  object{"type": "apiKey", "in": "cookie", "name": "access_token", "description": "Legacy HttpOnly access token cookie, accepted for backward compatibility."},
		"legacyRefreshCookie": object{"type": "apiKey", "in": "cookie", "name": "refresh_token", "description": "Legacy HttpOnly refresh token cookie, accepted by the refresh endpoint."},
	}
	paths := object{}
	schema := &schemas{definitions: definitions}
	oldPaths, _ := overrides["paths"].(map[string]any)
	tags := map[string]bool{}
	routes := Routes()
	sort.Slice(routes, func(i, j int) bool { return routes[i].Path+routes[i].Method < routes[j].Path+routes[j].Method })
	for _, route := range routes {
		key := strings.TrimSuffix(route.Handler, "-fm")
		f := source.functions[key]
		if f == nil {
			return nil, fmt.Errorf("no handler source for %s %s (%s)", route.Method, route.Path, key)
		}
		path := OpenAPIPath(route.Path)
		method := strings.ToLower(route.Method)
		op := buildOperation(source, schema, f, route)
		for oldPath, item := range oldPaths {
			if canonicalPath(oldPath) != canonicalPath(path) {
				continue
			}
			if methods, ok := item.(map[string]any); ok {
				if previous, ok := methods[method].(map[string]any); ok {
					for _, field := range []string{"summary", "description"} {
						if value, found := previous[field]; found {
							op[field] = value
						}
					}
					applyOverrides(op, previous)
				}
			}
		}
		if paths[path] == nil {
			paths[path] = object{}
		}
		paths[path].(object)[method] = op
		for _, tag := range op["tags"].([]string) {
			tags[tag] = true
		}
	}
	version, err := os.ReadFile(filepath.Join(dir, "VERSION"))
	if err != nil {
		return nil, err
	}
	tagList := []any{}
	names := []string{}
	for name := range tags {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		tagList = append(tagList, object{"name": name})
	}
	spec := object{
		"openapi": "3.0.3",
		"info":    object{"title": "MOH Integrated Health Portal API", "version": strings.TrimSpace(string(version)), "description": "Complete route inventory generated from the backend router and typed Go handlers. JSON request bodies, query/form parameters and response DTOs follow the source code. Protected routes accept a bearer JWT or an existing sso_session cookie. Permission and system/group checks remain enforced by the API. Login redirects should be followed in a browser. File endpoints stream binary content. Dynamic JSON/maps intentionally retain open schemas."},
		// Relative to /swagger/openapi.json: works at / and reverse-proxy /backend/ or /ssobackend/.
		"servers":  []any{object{"url": "..", "description": "Same backend origin and deployment prefix as this specification"}},
		"security": []any{object{"bearerAuth": []string{}}, object{"sessionCookie": []string{}}, object{"legacyAccessCookie": []string{}}},
		"tags":     tagList, "paths": paths, "components": components,
	}
	if err := Validate(spec); err != nil {
		return nil, err
	}
	var output bytes.Buffer
	output.WriteString(generatedHeader)
	encoder := yaml.NewEncoder(&output)
	encoder.SetIndent(2)
	if err := encoder.Encode(spec); err != nil {
		return nil, err
	}
	return output.Bytes(), nil
}

var parameterPattern = regexp.MustCompile(`\{[^}]+\}`)

func canonicalPath(path string) string { return parameterPattern.ReplaceAllString(path, "{}") }

var wordBoundary = regexp.MustCompile(`([a-z0-9])([A-Z])`)

func words(value string) string { return wordBoundary.ReplaceAllString(value, "$1 $2") }

func statusCode(f *function, expr ast.Expr) string {
	value := f.pkg.TypesInfo.Types[expr].Value
	if value != nil && value.Kind() == constant.Int {
		return value.ExactString()
	}
	return ""
}

func buildOperation(source *sources, schema *schemas, f *function, route gin.RouteInfo) object {
	tag := strings.ReplaceAll(filepath.Base(f.pkg.PkgPath), "_", "-")
	if strings.HasPrefix(route.Path, "/health") || route.Path == "/version" {
		tag = "platform"
	}
	if strings.Contains(route.Path, "/admin/") {
		tag = "admin-" + tag
	}
	op := object{"operationId": strings.ToLower(route.Method) + "_" + schemaName.ReplaceAllString(strings.Trim(route.Path, "/"), "_"), "summary": words(f.decl.Name.Name), "tags": []string{tag}, "x-go-handler": strings.TrimSuffix(route.Handler, "-fm")}
	if publicRoute(route.Path) {
		op["security"] = []any{}
	}
	if route.Path == "/api/v1/auth/me" {
		op["security"] = []any{object{"sessionCookie": []string{}}, object{"legacyAccessCookie": []string{}}}
	}
	if route.Path == "/api/v1/auth/refresh" {
		op["security"] = []any{object{"sessionCookie": []string{}}, object{"legacyRefreshCookie": []string{}}}
	}
	permissions := []string{}
	for permission := range source.permissions[functionKey(f.obj)+":"+route.Method] {
		permissions = append(permissions, permission)
	}
	sort.Strings(permissions)
	if len(permissions) > 0 {
		op["x-route-permissions"] = permissions
		op["description"] = "Explicit route permission: " + strings.Join(permissions, ", ") + ". Additional group/system access checks may apply."
	}
	parameters := map[string]object{}
	for _, name := range pathParameter.FindAllStringSubmatch(route.Path, -1) {
		parameters["path:"+name[1]] = object{"name": name[1], "in": "path", "required": true, "schema": object{"type": "string"}}
	}
	responses := object{}
	forms := object{}
	formRequired := map[string]bool{}
	multipart := false
	var requestSchemas []any
	optionalBody := false
	addParameter := func(name, location string, property object, required bool) {
		key := location + ":" + name
		if existing := parameters[key]; existing != nil {
			if required {
				existing["required"] = true
			}
			return
		}
		parameters[key] = object{"name": name, "in": location, "required": required, "schema": property}
	}
	source.walk(f, func(current *function, node ast.Node) {
		if assignment, ok := node.(*ast.AssignStmt); ok && len(assignment.Lhs) == 1 && len(assignment.Rhs) == 1 {
			if id, ok := assignment.Lhs[0].(*ast.Ident); ok && id.Name == "_" {
				if call, ok := assignment.Rhs[0].(*ast.CallExpr); ok {
					if selector, ok := call.Fun.(*ast.SelectorExpr); ok && selector.Sel.Name == "ShouldBindJSON" {
						optionalBody = true
					}
				}
			}
		}
		// MultipartForm.File["files"] can carry multiple files without FormFile().
		if index, ok := node.(*ast.IndexExpr); ok {
			if sel, ok := index.X.(*ast.SelectorExpr); ok && sel.Sel.Name == "File" {
				if name, ok := stringValue(current.pkg, index.Index); ok {
					forms[name] = object{"type": "array", "items": object{"type": "string", "format": "binary"}}
					multipart = true
				}
			}
		}
		call, ok := node.(*ast.CallExpr)
		if !ok {
			return
		}
		selector, ok := call.Fun.(*ast.SelectorExpr)
		if !ok {
			return
		}
		name := selector.Sel.Name
		obj := callee(current.pkg, call.Fun)
		owner := ""
		if obj != nil && obj.Pkg() != nil {
			owner = obj.Pkg().Path()
		}
		isGin := owner == "github.com/gin-gonic/gin"
		if isGin && len(call.Args) > 0 {
			switch name {
			case "Query", "DefaultQuery", "GetQuery", "QueryArray":
				if key, ok := stringValue(current.pkg, call.Args[0]); ok {
					property := object{"type": "string"}
					if name == "QueryArray" {
						property = object{"type": "array", "items": object{"type": "string"}}
					}
					if name == "DefaultQuery" && len(call.Args) > 1 {
						if value, ok := stringValue(current.pkg, call.Args[1]); ok {
							property["default"] = value
						}
					}
					addParameter(key, "query", property, false)
				}
			case "PostForm", "DefaultPostForm", "GetPostForm", "PostFormArray":
				if key, ok := stringValue(current.pkg, call.Args[0]); ok {
					forms[key] = object{"type": "string"}
					if name == "PostFormArray" {
						forms[key] = object{"type": "array", "items": object{"type": "string"}}
					}
				}
			case "FormFile":
				if key, ok := stringValue(current.pkg, call.Args[0]); ok {
					forms[key] = object{"type": "string", "format": "binary"}
					formRequired[key] = true
					multipart = true
				}
			case "ShouldBindJSON", "BindJSON":
				t := current.pkg.TypesInfo.TypeOf(call.Args[0])
				if ptr, ok := t.(*types.Pointer); ok {
					t = ptr.Elem()
				}
				requestSchemas = append(requestSchemas, schema.of(t))
			case "ShouldBindQuery", "BindQuery":
				t := current.pkg.TypesInfo.TypeOf(call.Args[0])
				if ptr, ok := t.(*types.Pointer); ok {
					t = ptr.Elem()
				}
				if n, ok := t.(*types.Named); ok {
					t = n.Underlying()
				}
				if value, ok := t.(*types.Struct); ok {
					for i := 0; i < value.NumFields(); i++ {
						field := value.Field(i)
						tag := reflect.StructTag(value.Tag(i))
						key := strings.Split(tag.Get("form"), ",")[0]
						if key == "" || key == "-" {
							continue
						}
						property := schema.of(field.Type())
						applyValidation(property, tag.Get("binding"))
						addParameter(key, "query", property, containsRule(tag.Get("binding"), "required"))
					}
				}
			case "MultipartForm":
				multipart = true
			case "GetHeader":
				if key, ok := stringValue(current.pkg, call.Args[0]); ok && !strings.EqualFold(key, "Authorization") && !strings.EqualFold(key, "Cookie") && !strings.EqualFold(key, "Content-Type") {
					addParameter(key, "header", object{"type": "string"}, false)
				}
			}
		}
		if (name == "FormFile" || name == "ParseMultipartForm") && owner == "net/http" {
			multipart = true
			if name == "FormFile" && len(call.Args) > 0 {
				if key, ok := stringValue(current.pkg, call.Args[0]); ok {
					forms[key] = object{"type": "string", "format": "binary"}
					formRequired[key] = true
				}
			}
		}
		if (name == "OK" || name == "Fail") && strings.HasSuffix(owner, "/internal/http/response") && len(call.Args) >= 3 {
			code := statusCode(current, call.Args[1])
			if code == "" {
				return
			}
			if name == "Fail" {
				responses[code] = errorResponse(code)
				return
			}
			value := schema.expression(current.pkg, call.Args[2])
			responseSchema := object{"type": "object", "required": []string{"success", "data"}, "properties": object{"success": object{"type": "boolean", "enum": []bool{true}}, "data": value, "meta": object{"type": "object", "properties": object{"requestId": object{"type": "string"}}}}}
			addResponse(responses, code, "application/json", responseSchema)
		}
		if isGin {
			switch name {
			case "Redirect":
				if len(call.Args) > 0 {
					if code := statusCode(current, call.Args[0]); code != "" {
						responses[code] = object{"description": "Redirect to browser login or configured portal destination.", "headers": object{"Location": object{"schema": object{"type": "string", "format": "uri-reference"}}}}
					}
				}
			case "JSON", "PureJSON", "IndentedJSON":
				if len(call.Args) > 1 {
					if code := statusCode(current, call.Args[0]); code != "" {
						addResponse(responses, code, "application/json", schema.expression(current.pkg, call.Args[1]))
					}
				}
			case "DataFromReader", "Data":
				if len(call.Args) > 0 {
					code := statusCode(current, call.Args[0])
					if code == "" {
						code = "200"
					}
					media := "application/octet-stream"
					idx := 1
					if name == "DataFromReader" {
						idx = 2
					}
					if len(call.Args) > idx {
						if v, ok := stringValue(current.pkg, call.Args[idx]); ok {
							media = v
						}
					}
					addResponse(responses, code, media, object{"type": "string", "format": "binary"})
				}
			case "File", "FileAttachment":
				addResponse(responses, "200", "application/octet-stream", object{"type": "string", "format": "binary"})
			case "Status":
				if len(call.Args) > 0 {
					if code := statusCode(current, call.Args[0]); code != "" {
						responses[code] = object{"description": http.StatusText(mustInt(code))}
					}
				}
			}
		}
	})
	bodyContent := object{}
	if len(requestSchemas) > 0 {
		body := requestSchemas[0]
		if len(requestSchemas) > 1 {
			body = object{"oneOf": dedupeSchemas(requestSchemas)}
		}
		bodyContent["application/json"] = object{"schema": body}
	}
	if len(forms) > 0 {
		required := []string{}
		for name := range formRequired {
			required = append(required, name)
		}
		sort.Strings(required)
		body := object{"type": "object", "properties": forms}
		if len(required) > 0 {
			body["required"] = required
		}
		media := "application/x-www-form-urlencoded"
		if multipart {
			media = "multipart/form-data"
		}
		bodyContent[media] = object{"schema": body}
	}
	if len(bodyContent) > 0 {
		op["requestBody"] = object{"required": !optionalBody, "content": bodyContent}
	}
	// Auth callback and launch parameters have explicit mandatory contracts.
	if route.Path == "/api/v1/auth/launch" {
		addParameter("returnTo", "query", object{"type": "string"}, true)
	}
	if route.Path == "/api/v1/auth/callback" {
		for _, name := range []string{"code", "state"} {
			addParameter(name, "query", object{"type": "string"}, true)
		}
	}
	keys := []string{}
	for key := range parameters {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	if len(keys) > 0 {
		list := []any{}
		for _, key := range keys {
			list = append(list, parameters[key])
		}
		op["parameters"] = list
	}
	if len(responses) == 0 {
		responses["200"] = object{"description": "Successful response. Payload is dynamically produced by this handler."}
	}
	responses["default"] = errorResponse("default")
	if !publicRoute(route.Path) {
		responses["401"] = errorResponse("401")
		responses["403"] = errorResponse("403")
	}
	if strings.HasPrefix(route.Path, "/api/") {
		responses["429"] = errorResponse("429")
	}
	op["responses"] = responses
	return op
}

func mustInt(value string) int { result, _ := strconv.Atoi(value); return result }
func errorResponse(code string) object {
	description := http.StatusText(mustInt(code))
	if description == "" {
		description = "Error response; error.code identifies the failure."
	}
	return object{"description": description, "content": object{"application/json": object{"schema": object{"$ref": "#/components/schemas/ErrorEnvelope"}}}}
}
func addResponse(responses object, code, media string, schema object) {
	if code == "204" {
		responses[code] = object{"description": "No content"}
		return
	}
	if previous, ok := responses[code].(object); ok {
		if content, ok := previous["content"].(object); ok {
			if existing, ok := content[media].(object); ok {
				if reflect.DeepEqual(existing["schema"], schema) {
					return
				}
				existing["schema"] = object{"anyOf": dedupeSchemas([]any{existing["schema"], schema})}
				return
			}
			content[media] = object{"schema": schema}
			return
		}
	}
	responses[code] = object{"description": http.StatusText(mustInt(code)), "content": object{media: object{"schema": schema}}}
}
func dedupeSchemas(values []any) []any {
	result := []any{}
	for _, value := range values {
		found := false
		for _, previous := range result {
			if reflect.DeepEqual(previous, value) {
				found = true
				break
			}
		}
		if !found {
			result = append(result, value)
		}
	}
	return result
}

// Supplemental form semantics are explicit: code binding reveals field types,
// but conditional business requirements cannot always be inferred statically.
func applyOverrides(op, previous object) {
	body, _ := op["requestBody"].(object)
	content, _ := body["content"].(object)
	media, _ := content["multipart/form-data"].(object)
	schema, _ := media["schema"].(object)
	if schema == nil {
		return
	}
	properties, _ := schema["properties"].(object)
	if additions, ok := previous["x-form-properties"].(object); ok {
		for name, value := range additions {
			properties[name] = value
		}
	}
	if additions, ok := previous["x-required-form-fields"].([]any); ok {
		keys := map[string]bool{}
		if old, ok := schema["required"].([]string); ok {
			for _, name := range old {
				keys[name] = true
			}
		}
		for _, value := range additions {
			if name, ok := value.(string); ok {
				keys[name] = true
			}
		}
		required := []string{}
		for name := range keys {
			required = append(required, name)
		}
		sort.Strings(required)
		schema["required"] = required
	}
}
