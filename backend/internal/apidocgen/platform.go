package apidocgen

import (
	"bytes"
	"fmt"
	"sort"
	"strings"

	"go.yaml.in/yaml/v3"
)

// PlatformContractFile is the published platform API contract, relative to the
// backend directory. It lives in the standard-library-only core module so
// other repositories can consume it alongside the identity-sync contract.
const PlatformContractFile = "core/platform/contract/platform.openapi.yaml"

// PlatformContractVersion is the platform API contract version. Bump the minor
// version for additive changes and the major version (with a new /api/vN path)
// for breaking ones; see core/platform/contract/README.md.
const PlatformContractVersion = "1.0.0"

const platformPathPrefix = "/api/v1/platform/"

const platformContractHeader = "# Generated by go run ./cmd/cli openapi generate from backend/docs/openapi.yaml. Do not edit.\n"

const platformContractDescription = `Endpoints the MoH Integrated Health Portal offers to application backends:
caller identity, readiness, notifications and per-user access decisions.

Every call needs a Bearer access token from the portal's Keycloak realm with
the platform audience (default moh-platform-api) and the capability scope the
endpoint names. Machine clients must be bound to their application in the
portal registry; effective scopes are the token's scopes that the binding
also grants.

Guide: docs/integrations/platform-api.md. Authorization rules:
docs/platform-identity.md. Compatibility policy:
backend/core/platform/contract/README.md.

This file is generated from the portal's full API description and checked in
CI, so it always matches the deployed routes.`

// PlatformContract extracts the platform API contract from the full generated
// OpenAPI document: only /api/v1/platform/* paths, the component schemas they
// reference (transitively), bearer authentication only, and no internal
// x-go-* annotations.
func PlatformContract(full []byte) ([]byte, error) {
	var spec object
	if err := yaml.Unmarshal(dropHeader(full), &spec); err != nil {
		return nil, fmt.Errorf("parse OpenAPI document: %w", err)
	}
	allPaths, _ := spec["paths"].(object)
	components, _ := spec["components"].(object)
	allSchemas, _ := components["schemas"].(object)

	paths := object{}
	for path, item := range allPaths {
		if strings.HasPrefix(path, platformPathPrefix) {
			paths[path] = stripInternal(item)
		}
	}
	if len(paths) == 0 {
		return nil, fmt.Errorf("no %s paths in the OpenAPI document", platformPathPrefix)
	}

	schemas := object{}
	pending := collectRefs(paths, nil)
	for len(pending) > 0 {
		name := pending[0]
		pending = pending[1:]
		if _, done := schemas[name]; done {
			continue
		}
		definition, ok := allSchemas[name]
		if !ok {
			return nil, fmt.Errorf("platform contract references missing schema %s", name)
		}
		schemas[name] = stripInternal(definition)
		pending = collectRefs(definition, pending)
	}

	contract := object{
		"openapi": "3.0.3",
		"info": object{
			"title":       "MoH Integrated Health Portal platform API",
			"version":     PlatformContractVersion,
			"description": platformContractDescription,
		},
		"servers": []any{object{
			"url":       "https://{portal}",
			"variables": object{"portal": object{"default": "portals.health.go.ug"}},
		}},
		"security": []any{object{"bearerAuth": []string{}}},
		"tags":     []any{object{"name": "platform"}},
		"paths":    paths,
		"components": object{
			"schemas": schemas,
			"securitySchemes": object{"bearerAuth": object{
				"type": "http", "scheme": "bearer", "bearerFormat": "JWT",
				"description": "Keycloak access token with the platform audience and the endpoint's capability scope. Cookies are not accepted.",
			}},
		},
	}
	var output bytes.Buffer
	output.WriteString(platformContractHeader)
	encoder := yaml.NewEncoder(&output)
	encoder.SetIndent(2)
	if err := encoder.Encode(contract); err != nil {
		return nil, err
	}
	return output.Bytes(), nil
}

// dropHeader removes leading comment lines so the YAML parses as a document.
func dropHeader(data []byte) []byte {
	for bytes.HasPrefix(data, []byte("#")) {
		if i := bytes.IndexByte(data, '\n'); i >= 0 {
			data = data[i+1:]
		} else {
			return nil
		}
	}
	return data
}

// stripInternal deep-copies value without x-go-* keys.
func stripInternal(value any) any {
	switch v := value.(type) {
	case map[string]any:
		out := make(map[string]any, len(v))
		for key, item := range v {
			if !strings.HasPrefix(key, "x-go-") {
				out[key] = stripInternal(item)
			}
		}
		return out
	case []any:
		out := make([]any, len(v))
		for i, item := range v {
			out[i] = stripInternal(item)
		}
		return out
	}
	return value
}

const schemaRefPrefix = "#/components/schemas/"

// collectRefs appends the component schema names value references, sorted for
// deterministic traversal.
func collectRefs(value any, names []string) []string {
	var found []string
	var walk func(any)
	walk = func(value any) {
		switch v := value.(type) {
		case map[string]any:
			if ref, ok := v["$ref"].(string); ok && strings.HasPrefix(ref, schemaRefPrefix) {
				found = append(found, strings.TrimPrefix(ref, schemaRefPrefix))
			}
			for _, item := range v {
				walk(item)
			}
		case []any:
			for _, item := range v {
				walk(item)
			}
		}
	}
	walk(value)
	sort.Strings(found)
	return append(names, found...)
}
